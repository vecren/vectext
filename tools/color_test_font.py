import sys
from fontTools.fontBuilder import FontBuilder
from fontTools.pens.ttGlyphPen import TTGlyphPen
from fontTools.colorLib.builder import buildCOLR, buildCPAL

builder = FontBuilder(1000, isTTF=True)
builder.setupGlyphOrder([".notdef", "space", "A", "paint"])
builder.setupCharacterMap({32: "space", 65: "A"})
glyphs = {}
for name in [".notdef", "space", "A", "paint"]:
    pen = TTGlyphPen(None)
    if name in [".notdef", "paint"]:
        pen.moveTo((50, 0))
        pen.lineTo((550, 0))
        pen.lineTo((550, 700))
        pen.lineTo((50, 700))
        pen.closePath()
    glyphs[name] = pen.glyph()
builder.setupGlyf(glyphs)
builder.setupHorizontalMetrics({name: (600, 0) for name in glyphs})
builder.setupHorizontalHeader(ascent=800, descent=-200)
builder.setupNameTable({"familyName": "Vectext Test Color", "styleName": "Regular",
                        "uniqueFontIdentifier": "vectext-test-color-1",
                        "fullName": "Vectext Test Color Regular", "psName": "VectextTestColor",
                        "version": "Version 1.0", "copyright": "CC0; generated by vectext/tools/color_test_font.py"})
builder.setupOS2(sTypoAscender=800, sTypoDescender=-200, usWinAscent=800, usWinDescent=200)
builder.setupPost()
builder.font["COLR"] = buildCOLR({"A": [("paint", 0)]})
builder.font["CPAL"] = buildCPAL([[(1.0, 0.0, 0.0, 1.0)]])
builder.font["head"].created = builder.font["head"].modified = 2082844800
builder.font.recalcTimestamp = False
builder.save(sys.argv[1])
