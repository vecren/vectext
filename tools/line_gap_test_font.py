import sys
from fontTools.fontBuilder import FontBuilder
from fontTools.pens.ttGlyphPen import TTGlyphPen

builder = FontBuilder(1000, isTTF=True)
names = [".notdef", "space", "A", "g"]
builder.setupGlyphOrder(names)
builder.setupCharacterMap({32: "space", 65: "A", 103: "g"})
glyphs = {}
for name in names:
    pen = TTGlyphPen(None)
    if name != "space":
        bottom = -200 if name == "g" else 0
        pen.moveTo((50, bottom))
        pen.lineTo((550, bottom))
        pen.lineTo((550, 700))
        pen.lineTo((50, 700))
        pen.closePath()
    glyphs[name] = pen.glyph()
builder.setupGlyf(glyphs)
builder.setupHorizontalMetrics({name: (600, 50) for name in names})
builder.setupHorizontalHeader(ascent=800, descent=-200, lineGap=1000)
builder.setupNameTable({
    "familyName": "Vectext Test Leading", "styleName": "Regular",
    "uniqueFontIdentifier": "vectext-test-leading-1",
    "fullName": "Vectext Test Leading Regular", "psName": "VectextTestLeading",
    "version": "Version 1.0",
    "copyright": "CC0; generated by vectext/tools/line_gap_test_font.py",
})
builder.setupOS2(sTypoAscender=800, sTypoDescender=-200, sTypoLineGap=1000,
                 usWinAscent=800, usWinDescent=200)
builder.setupPost()
builder.font["head"].created = builder.font["head"].modified = 2082844800
builder.font.recalcTimestamp = False
builder.save(sys.argv[1])
